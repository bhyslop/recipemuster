/// THE KIND DECIDES WHICH DEPENDENCIES COUNT, and this is the pair that shows
/// it: one lure, one manifest, one dev-dependency, and two collars over it that
/// differ in their kind and in nothing else that matters here.
///
/// The app is SOUND while naming neither `probe` in its allow list nor its
/// directory in its roots, because cargo compiles a dev-dependency into a test
/// target and never into a binary. The suite carrying the same omission is not.
/// Driven as a pair rather than as two hurdles: either half alone would pass
/// under a validator that simply ignored dev-dependencies, and only the contrast
/// says the kind did the work.
#[test]
fn bktr_the_kind_decides_whether_a_dev_dependency_counts() {
    let lure = zbktr_kennel("dev-kind");

    lure.bktu_write("app-lure/bkrr.env", ZBKTR_APP);
    let app = zbktr_findings(&lure, "app-lure");
    assert!(
        app.is_empty(),
        "an app is not compiled with its crate's dev-dependencies, so it owes no declaration \
         about one: {:?}",
        app
    );

    lure.bktu_write(
        "suite-lure/bkrr.env",
        &ZBKTR_SOUND
            .replace("  probe \\\n", "")
            .replace("BKRR_TAMED_CRATES=\"inner probe\"", "BKRR_TAMED_CRATES=\"inner\""),
    );
    let suite = zbktr_findings(&lure, "suite-lure");

    assert_eq!(suite.len(), 2, "findings: {:?}", suite);
    assert!(
        suite.iter().any(|held| held.contains("BKRR_TAMED_CRATES") && held.contains("probe")),
        "findings: {:?}",
        suite
    );
    assert!(
        suite.iter().any(|held| held.contains("BKRR_ROOTS") && held.contains("probe")),
        "findings: {:?}",
        suite
    );
}

