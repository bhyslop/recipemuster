//! The resolver's hurdles, driven over a lure carrying a real two-crate closure.
//!
//! EVERY PROOF IS DRIVEN AGAINST REAL CARGO. The closure reading and the
//! direct-dependency reading are the two this crate could most easily fake, and
//! faking them would prove only that a fixture agrees with itself: the lure
//! stands up an actual crate with an actual path dependency, and cargo is asked
//! about it through the leash exactly as a door would ask.
//!
//! THE INVERSIONS ARE PLANTED IN THE LURE, never in a committed collar. A
//! fixture collar standing in this repository would be a real collar to every
//! door that walks the tree, which is the reason lures exist at all
//! (BKSLR-Lure.adoc).

use super::bkcr_resolve::{bkcr_resolve, bkcr_walk};
use super::bktu_lure::bktu_Lure;

/// The collar the lure carries when nothing is inverted.
const ZBKTR_SOUND: &str = "\
BKRR_COLLAR=\"suite-lure\"
BKRR_KIND=\"bknre_suite\"
BKRR_MANIFEST=\"Cargo.toml\"
BKRR_TARGET=\"bknre_manifest\"
BKRR_ROOTS=\"src \\
  inner \\
  probe \\
  Cargo.toml\"
BKRR_FEATURES=\"\"
BKRR_PROFILE=\"test\"
BKRR_SPEND=\"bknre_reader\"
BKRR_TAMED_CRATES=\"inner probe\"
BKRR_FERAL_CRATES=\"bknre_tamed\"
BKRR_MUZZLE=\".\"
BKRR_EXERGUE=\"bknre_unstruck\"
BKRR_RUNNER=\"bknre_cargo\"
BKRR_TONGUE=\"bknre_harness\"
";

/// The same collar declaring an APP rather than a suite, and dropping the
/// dev-dependency from both proofs — which is what makes it sound: cargo
/// compiles a dev-dependency into a test target and never into a binary.
const ZBKTR_APP: &str = "\
BKRR_COLLAR=\"app-lure\"
BKRR_KIND=\"bknre_app\"
BKRR_MANIFEST=\"Cargo.toml\"
BKRR_TARGET=\"lure\"
BKRR_ROOTS=\"src \\
  inner \\
  Cargo.toml\"
BKRR_FEATURES=\"\"
BKRR_PROFILE=\"release\"
BKRR_SPEND=\"bknre_reader\"
BKRR_TAMED_CRATES=\"inner\"
BKRR_FERAL_CRATES=\"bknre_tamed\"
BKRR_MUZZLE=\".\"
BKRR_EXERGUE=\"bknre_unstruck\"
BKRR_RESIDENCE=\"target/release\"
BKRR_BYNAME=\"lure\"
";

/// Stand up a lure holding a crate, a local dependency of that crate, a local
/// DEV dependency beside it, a muzzle, and one sound collar over all of it.
fn zbktr_kennel(name: &str) -> bktu_Lure {
    let lure = bktu_Lure::bktu_compose(name);

    lure.bktu_write(
        "Cargo.toml",
        "[package]\nname = \"lure\"\nversion = \"0.0.1\"\nedition = \"2021\"\n\
         [lib]\nname = \"lure\"\npath = \"src/lib.rs\"\n\
         [dependencies]\ninner = { path = \"inner\" }\n\
         [dev-dependencies]\nprobe = { path = \"probe\" }\n",
    );
    lure.bktu_write(
        "Cargo.lock",
        "# This file is automatically @generated by Cargo.\n\
         # It is not intended for manual editing.\n\
         version = 4\n\n\
         [[package]]\nname = \"inner\"\nversion = \"0.0.1\"\n\n\
         [[package]]\nname = \"lure\"\nversion = \"0.0.1\"\n\
         dependencies = [\n \"inner\",\n \"probe\",\n]\n\n\
         [[package]]\nname = \"probe\"\nversion = \"0.0.1\"\n",
    );
    lure.bktu_write("src/lib.rs", "// eof\n");
    lure.bktu_write(
        "inner/Cargo.toml",
        "[package]\nname = \"inner\"\nversion = \"0.0.1\"\nedition = \"2021\"\n\
         [lib]\nname = \"inner\"\npath = \"src/lib.rs\"\n",
    );
    lure.bktu_write("inner/src/lib.rs", "// eof\n");
    lure.bktu_write(
        "probe/Cargo.toml",
        "[package]\nname = \"probe\"\nversion = \"0.0.1\"\nedition = \"2021\"\n\
         [lib]\nname = \"probe\"\npath = \"src/lib.rs\"\n",
    );
    lure.bktu_write("probe/src/lib.rs", "// eof\n");
    lure.bktu_write("clippy.toml", "# the lure's muzzle\n");
    lure.bktu_write("suite-lure/bkrr.env", ZBKTR_SOUND);
    lure.bktu_commit("stand the collar up");

    lure
}

/// Every finding against the lure's collar, as one string a hurdle can read.
fn zbktr_findings(lure: &bktu_Lure, name: &str) -> Vec<String> {
    bkcr_resolve(lure.bktu_root(), name)
        .unwrap_or_else(|err| panic!("'{}' should resolve in the lure: {}", name, err))
        .findings
}

/// The walk finds a collar wherever it stands, and steps over a build directory
/// rather than reading whatever a compiler happened to leave there.
#[test]
fn bktr_the_walk_finds_collars_and_steps_over_a_build_directory() {
    let lure = zbktr_kennel("walk");
    lure.bktu_write("target/suite-lure/bkrr.env", ZBKTR_SOUND);
    lure.bktu_write("inner/app-inner/bkrr.env", ZBKTR_SOUND);

    let found = bkcr_walk(lure.bktu_root()).expect("the lure is walkable");

    let named: Vec<String> = found
        .iter()
        .map(|held| held.display().to_string())
        .collect();

    assert!(named.contains(&"suite-lure".to_string()), "found: {:?}", named);
    assert!(named.contains(&"inner/app-inner".to_string()), "found: {:?}", named);
    assert!(
        !named.iter().any(|held| held.starts_with("target")),
        "a build directory holds no collar and is stepped over by name: {:?}",
        named
    );
}

/// THE CONTROL FOR EVERY INVERSION BELOW. A sound collar carries no finding at
/// all — which is what makes each inversion's finding a statement about the
/// inversion rather than about the fixture.
#[test]
fn bktr_a_sound_collar_carries_no_finding() {
    let lure = zbktr_kennel("sound");
    let findings = zbktr_findings(&lure, "suite-lure");

    assert!(
        findings.is_empty(),
        "the sound collar must carry no finding, and it carries: {:?}",
        findings
    );
}

/// The identity law: the declared name and the instance directory's name are
