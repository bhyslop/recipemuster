/// THE PRESENCE READING EVERY COMPILE ROAD TAKES, proven here at the one place
/// it is implemented so the three roads can be proven to CALL it rather than
/// each re-proving what it says.
///
/// BOTH ARMS, and the standing arm is what keeps the absent arm honest: a
/// reading that refused unconditionally would pass the first assertion having
/// proven nothing about whether it can tell a file that stands from one that
/// does not.
#[test]
fn bktr_an_absent_exergue_refuses_and_names_the_doors() {
    let lure = zbktr_kennel("exergue-absent");
    lure.bktu_write(
        "suite-lure/bkrr.env",
        &ZBKTR_SOUND.replace(
            "BKRR_EXERGUE=\"bknre_unstruck\"",
            "BKRR_EXERGUE=\"src/gen_exergue.rs\"\nBKRR_STRIKE=\"tt/lure-b.Build.sh\"",
        ),
    );

    let resolved =
        bkcr_resolve(lure.bktu_root(), "suite-lure").expect("the collar should resolve");

    let refusal = super::bkcr_resolve::bkcr_exergue_stands(lure.bktu_root(), &resolved.collar)
        .expect_err("an exergue that does not stand refuses");
    assert!(
        refusal.contains("src/gen_exergue.rs"),
        "it names the file that is missing: {}",
        refusal
    );
    assert!(
        refusal.contains("tt/lure-b.Build.sh"),
        "it names the door that writes it, which is the whole reason this reading exists: {}",
        refusal
    );

    // THE SAME COLLAR, THE FILE NOW STANDING. Nothing else moves, so a reading
    // that still refused would be refusing on the declaration rather than on the
    // tree.
    lure.bktu_write("src/gen_exergue.rs", "// struck by the hurdle\n");
    super::bkcr_resolve::bkcr_exergue_stands(lure.bktu_root(), &resolved.collar)
        .expect("an exergue that stands is no refusal");

    // AND A COLLAR DECLARING NONE IS UNAFFECTED, which is what every other
    // collar in the estate declares: the reading must be silent there, or it
    // would refuse over a tree that owes it nothing. Proven against the sound
    // collar, whose declaration is the unstruck token and whose named file was
    // never written.
    lure.bktu_write("suite-lure/bkrr.env", ZBKTR_SOUND);
    let unstruck =
        bkcr_resolve(lure.bktu_root(), "suite-lure").expect("the collar should resolve");
    assert!(
        unstruck.collar.bkcr_exergue().is_empty(),
        "the unstruck token declares no exergue to stand"
    );
    super::bkcr_resolve::bkcr_exergue_stands(lure.bktu_root(), &unstruck.collar)
        .expect("a collar declaring no exergue is never refused for one");
}
